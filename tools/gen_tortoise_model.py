"""Writes the layer of the Sylvan Tortoise (alpha of the forest) into TortoiseModel.java, from its Blockbench file,
and draws its glow texture (the yellow eyes) from the texture painted in Blockbench.

Run from the project folder after a change of tools/models/tortue_sylve_v2.bbmodel:
    python tools/gen_tortoise_model.py
It also writes the texture embedded in the Blockbench file to
src/main/resources/assets/bdragon/textures/entity/alpha/forest_tortoise.png, its glow (the eyes) next to it, and the
texture of the magic clouds under its paws (forest_tortoise_clouds.png, 64 x 32 units painted at 2 texels per unit).

The groups of the Blockbench file become the parts of the model (body > neck > head > jaw, tail, thigh0..3 > shin,
spikes, garden), with the pivots, rotations and texture offsets of the file (box UV), converted like the Blockbench
Java exporter does (x and y flipped, rotations x and y negated). The animation (TortoiseModel.setupAnim) relies on
these names and on the pivots of the neck, head, jaw, tail and legs.
"""
import base64
import io
import json
import os
import re

import storm_model
from gen_storm_model import Writer

HERE = storm_model.HERE
BBMODEL = os.path.join(HERE, 'models', 'tortue_sylve_v2.bbmodel')
PROJECT = os.path.dirname(HERE)
JAVA = os.path.join(PROJECT, 'src', 'main', 'java', 'com', 'yb', 'dragons', 'client', 'model', 'TortoiseModel.java')
TEXTURES = os.path.join(PROJECT, 'src', 'main', 'resources', 'assets', 'bdragon', 'textures', 'entity', 'alpha')
BEGIN = '        // <generated by tools/gen_tortoise_model.py>'
END = '        // </generated>'
# the cubes that glow in the dark (drawn again with the "eyes" render type)
GLOWING = ('eye',)


class Model(storm_model.Model):
    """Reads the groups by their place in the outliner (the four legs each have a group named "shin")."""

    def __init__(self, path):
        super().__init__(path)
        self.nodes = {}
        bb = json.load(open(path, encoding='utf-8'))

        def index(node):
            if isinstance(node, str):
                return
            self.nodes[node['uuid']] = node
            for c in node['children']:
                index(c)
        for n in bb['outliner']:
            index(n)
        self.roots = [n for n in bb['outliner'] if not isinstance(n, str)]

    def node_part(self, node, parent_origin):
        g = self.groups[node['uuid']]
        origin = g['origin']
        p = storm_model.Part(g['name'].lower(), storm_model.conv(storm_model.sub(origin, parent_origin)),
                             storm_model.conv_rot(g.get('rotation')))
        k = 0
        for c in node['children']:
            if isinstance(c, str):
                e = self.elements[c]
                if e.get('export') is False:
                    continue
                if storm_model.nonzero(e.get('rotation')):
                    sp = storm_model.Part('r%d' % k, storm_model.conv(storm_model.sub(e['origin'], origin)),
                                          storm_model.conv_rot(e['rotation']))
                    k += 1
                    sp.cubes.append(storm_model.box(e, e['origin']))
                    p.children.append(sp)
                else:
                    p.cubes.append(storm_model.box(e, origin))
            else:
                p.children.append(self.node_part(c, origin))
        return p


def layer():
    model = Model(BBMODEL)
    root = [n for n in model.roots if model.groups[n['uuid']]['name'] == 'body'][0]
    body = model.node_part(root, (0, 24, 0))
    w = Writer()
    w.part(body, 'root')
    w.lines.append('        return LayerDefinition.create(mesh, %d, %d);' % model.texture)
    return model, w


def textures(model):
    """The texture of the Blockbench file and its glow (only the faces of the glowing cubes are kept)."""
    from PIL import Image
    bb = json.load(open(BBMODEL, encoding='utf-8'))
    src = bb['textures'][0]['source']
    img = Image.open(io.BytesIO(base64.b64decode(src.split(',', 1)[1]))).convert('RGBA')
    tw, th = model.texture
    k = img.width / tw
    glow = Image.new('RGBA', img.size, (0, 0, 0, 0))
    for e in bb['elements']:
        if e['name'] not in GLOWING:
            continue
        u, v = e.get('uv_offset') or [0, 0]
        w = e['to'][0] - e['from'][0]
        h = e['to'][1] - e['from'][1]
        d = e['to'][2] - e['from'][2]
        box = tuple(int(round(a * k)) for a in (u, v, u + 2 * (d + w), v + d + h))
        glow.paste(img.crop(box), box[:2])
    return img, glow


def clouds():
    """Soft white-blue puffs, slightly translucent (TortoiseCloudModel)."""
    import numpy as np
    from PIL import Image
    rng = np.random.default_rng(20261029)
    pal = np.array([[0xc4, 0xcf, 0xdd], [0xe1, 0xe8, 0xf2], [0xf4, 0xf7, 0xfd], [0xff, 0xff, 0xff]], float)
    h, w = 64, 128
    ys = np.mgrid[0:h, 0:w][0]
    t = np.clip(0.95 - 0.55 * (ys % 24) / 24 + rng.uniform(-0.08, 0.08, (h, w)), 0, 0.999) * (len(pal) - 1)
    i = t.astype(int)
    f = (t - i)[..., None]
    rgb = pal[i] * (1 - f) + pal[np.minimum(i + 1, len(pal) - 1)] * f
    a = rng.uniform(205, 240, (h, w))[..., None]
    return Image.fromarray(np.concatenate([rgb, a], -1).astype(np.uint8), 'RGBA')


def main():
    model, w = layer()
    code = '\n'.join(w.lines)
    src = open(JAVA, encoding='utf-8').read()
    pattern = re.compile(re.escape(BEGIN) + '.*?' + re.escape(END), re.S)
    if not pattern.search(src):
        raise SystemExit('markers not found in ' + JAVA)
    src = pattern.sub(lambda m: BEGIN + '\n' + code + '\n' + END, src)
    with open(JAVA, 'w', encoding='utf-8', newline='\n') as out:
        out.write(src)
    img, glow = textures(model)
    img.save(os.path.join(TEXTURES, 'forest_tortoise.png'))
    glow.save(os.path.join(TEXTURES, 'forest_tortoise_glow.png'))
    clouds().save(os.path.join(TEXTURES, 'forest_tortoise_clouds.png'))
    print('%d parts written, texture %dx%d' % (w.n, *model.texture))


if __name__ == '__main__':
    main()
