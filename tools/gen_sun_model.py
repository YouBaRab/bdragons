"""Writes the Sun Steed (alpha of the sunlight) into the game, from its Blockbench file
tools/models/dragon_soleil_alpha.bbmodel (made by tools/build_sun_alpha.py, then retouched in Blockbench):

- the layer of SunSteedModel.java (between its <generated> markers): the groups of the file become the parts of the
  model (same names, same nesting; a name repeated under one parent gets a number), with the pivots, the rotations and
  the texture offsets of the file (box UV), converted like the Blockbench Java exporter does;
- SunSteedAnimations.java: the animations of the file (idle, walk, fly, ult, sun_spin, sun_afk, sun_rebuild) as
  keyframes, played by SunSteedModel exactly like Blockbench plays them;
- the texture (sun_steed.png) and its glow (sun_steed_glow.png: the sun, the halo and the eyes shine in the dark).

Run from the project folder after a change of the Blockbench file:
    python tools/gen_sun_model.py
"""
import base64
import io
import json
import os
import re

from PIL import Image

import storm_model
from gen_storm_model import Writer, f

HERE = storm_model.HERE
PROJECT = os.path.dirname(HERE)
BBMODEL = os.path.join(HERE, 'models', 'dragon_soleil_alpha.bbmodel')
MODEL_DIR = os.path.join(PROJECT, 'src', 'main', 'java', 'com', 'yb', 'dragons', 'client', 'model')
JAVA = os.path.join(MODEL_DIR, 'SunSteedModel.java')
ANIMS = os.path.join(MODEL_DIR, 'SunSteedAnimations.java')
TEXTURES = os.path.join(PROJECT, 'src', 'main', 'resources', 'assets', 'bdragon', 'textures', 'entity', 'alpha')
BEGIN = '        // <generated by tools/gen_sun_model.py>'
END = '        // </generated>'
# the cubes whose texture shines in the dark
GLOWING = ('sun', 'halo', 'eye_l', 'eye_r')


def main():
    bb = json.load(open(BBMODEL, encoding='utf-8'))
    elements = {e['uuid']: e for e in bb['elements']}
    groups = {g['uuid']: g for g in bb['groups']}
    paths = {}          # group uuid -> path of the part in the game ("body/neck/head")

    def part(node, parent_origin, parent_path, used):
        g = groups[node['uuid']]
        name = g['name'].lower()
        n, k = name, 1
        while n in used:
            k += 1
            n = '%s%d' % (name, k)
        used.add(n)
        path = (parent_path + '/' if parent_path else '') + n
        paths[node['uuid']] = path
        origin = g['origin']
        p = storm_model.Part(n, storm_model.conv(storm_model.sub(origin, parent_origin)), storm_model.conv_rot(g.get('rotation')))
        names = set()
        r = 0
        for c in node['children']:
            if isinstance(c, str):
                e = elements[c]
                if e.get('export') is False:
                    continue
                if storm_model.nonzero(e.get('rotation')):
                    while 'r%d' % r in names:
                        r += 1
                    sp = storm_model.Part('r%d' % r, storm_model.conv(storm_model.sub(e['origin'], origin)),
                                          storm_model.conv_rot(e['rotation']))
                    names.add('r%d' % r)
                    sp.cubes.append(storm_model.box(e, e['origin']))
                    p.children.append(sp)
                else:
                    p.cubes.append(storm_model.box(e, origin))
            else:
                p.children.append(part(c, origin, path, names))
        return p

    roots = [n for n in bb['outliner'] if not isinstance(n, str)]
    w = Writer()
    used = set()
    for node in roots:
        w.part(part(node, (0, 24, 0), '', used), 'root')
    tw, th = bb['resolution']['width'], bb['resolution']['height']
    w.lines.append('        return LayerDefinition.create(mesh, %d, %d);' % (tw, th))
    src = open(JAVA, encoding='utf-8').read()
    pattern = re.compile(re.escape(BEGIN) + '.*?' + re.escape(END), re.S)
    if not pattern.search(src):
        raise SystemExit('markers not found in ' + JAVA)
    src = pattern.sub(lambda m: BEGIN + '\n' + '\n'.join(w.lines) + '\n' + END, src)
    with open(JAVA, 'w', encoding='utf-8', newline='\n') as out:
        out.write(src)

    # --- the animations ---------------------------------------------------------------------------------------
    bones = []
    anims = []
    for a in bb.get('animations', []):
        name = a['name'].split('.')[-1].upper()
        channels = []
        for uid, an in a['animators'].items():
            if uid not in paths:
                continue
            path = paths[uid]
            if path not in bones:
                bones.append(path)
            for ch, kind in (('rotation', 0), ('position', 1), ('scale', 2)):
                keys = sorted((k for k in an['keyframes'] if k['channel'] == ch), key=lambda k: k['time'])
                if not keys:
                    continue
                times = ', '.join(f(k['time']) for k in keys)
                values = ', '.join('%s, %s, %s' % tuple(f(float(k['data_points'][0][c])) for c in 'xyz') for k in keys)
                modes = ', '.join({'linear': '0', 'catmullrom': '1', 'step': '2'}.get(k.get('interpolation'), '0') for k in keys)
                channels.append('            new Channel(%d, %d, new float[] {%s},\n                    new float[] {%s},\n'
                                '                    new byte[] {%s})' % (bones.index(path), kind, times, values, modes))
        anims.append('    public static final Anim %s = new Anim(%sF, %s,\n%s);' % (
            name, a['length'], 'true' if a['loop'] == 'loop' else 'false', ',\n'.join(channels)))
    code = ANIM_HEAD + '    /** The animated parts (paths from the root of the model). */\n    public static final String[] BONES = {%s};\n\n' % (
        ', '.join('"%s"' % b for b in bones)) + '\n\n'.join(anims) + '\n\n' + ANIM_TAIL
    with open(ANIMS, 'w', encoding='utf-8', newline='\n') as out:
        out.write(code)

    # --- the textures -----------------------------------------------------------------------------------------
    img = Image.open(io.BytesIO(base64.b64decode(bb['textures'][0]['source'].split(',', 1)[1]))).convert('RGBA')
    img.save(os.path.join(TEXTURES, 'sun_steed.png'))
    glow = Image.new('RGBA', img.size, (0, 0, 0, 0))
    for e in bb['elements']:
        if e['name'] not in GLOWING:
            continue
        u, v = e.get('uv_offset') or [0, 0]
        sw, sh, sd = (int(round(e['to'][i] - e['from'][i])) for i in range(3))
        box = (int(u), int(v), int(u) + 2 * (sw + sd), int(v) + sd + sh)
        glow.paste(img.crop(box), box[:2])
    glow.save(os.path.join(TEXTURES, 'sun_steed_glow.png'))
    print('%d parts, %d animations, %d animated bones, texture %dx%d' % (w.n, len(anims), len(bones), tw, th))


ANIM_HEAD = '''package com.yb.dragons.client.model;

import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.util.Mth;

/**
 * The animations of the Sun Steed (alpha of the sunlight), written by {@code tools/gen_sun_model.py} from its Blockbench
 * file {@code tools/models/dragon_soleil_alpha.bbmodel}: do not change them here, change the Blockbench file and run the
 * script again.
 *
 * <p>They are played like Blockbench plays them (Modded Entity format): every keyframe value is added to the rest pose
 * of its group (rotations in degrees, positions in pixels, scales as factors); between two keyframes the value is
 * linear, smooth (Catmull-Rom, when one of the two is smooth) or held (step).</p>
 */
public final class SunSteedAnimations {
    /** A channel of one part: kind 0 = rotation, 1 = position, 2 = scale; mode of each key: 0 linear, 1 smooth, 2 step. */
    public record Channel(int bone, int kind, float[] times, float[] values, byte[] modes) {
        /** The value of the channel (x, y, z) at this time (seconds), into out. */
        void sample(float t, float[] out) {
            int n = times.length;
            if (t <= times[0] || n == 1) {
                set(out, 0);
                return;
            }
            if (t >= times[n - 1]) {
                set(out, n - 1);
                return;
            }
            int i = 0;
            while (i < n - 2 && t >= times[i + 1]) i++;
            float k = (t - times[i]) / Math.max(1.0E-6F, times[i + 1] - times[i]);
            if (modes[i] == 2) {
                set(out, i);
                return;
            }
            boolean smooth = modes[i] == 1 || modes[i + 1] == 1;
            for (int c = 0; c < 3; c++) {
                float p1 = values[i * 3 + c], p2 = values[(i + 1) * 3 + c];
                if (smooth) {
                    float p0 = i > 0 ? values[(i - 1) * 3 + c] : p1;
                    float p3 = i + 2 < n ? values[(i + 2) * 3 + c] : p2;
                    out[c] = catmullRom(k, p0, p1, p2, p3);
                } else {
                    out[c] = Mth.lerp(k, p1, p2);
                }
            }
        }

        private void set(float[] out, int i) {
            out[0] = values[i * 3];
            out[1] = values[i * 3 + 1];
            out[2] = values[i * 3 + 2];
        }
    }

    /** An animation: its length (seconds), whether it loops, its channels. */
    public record Anim(float length, boolean loop, Channel... channels) {
        /** The time of the animation (seconds) for a time since its start: wrapped when it loops, held at its end. */
        public float time(float seconds) {
            if (loop) return length <= 0 ? 0 : seconds - length * Mth.floor(seconds / length);
            return Mth.clamp(seconds, 0, length);
        }

        /**
         * Adds this animation at the given time (seconds since its start) to the parts, with a weight (0..1).
         * @param skip a bone index that is not played (-1 = none)
         */
        public void apply(ModelPart[] parts, float seconds, float weight, int skip) {
            if (weight <= 0) return;
            float t = time(seconds);
            float[] v = new float[3];
            for (Channel ch : channels) {
                if (ch.bone == skip) continue;
                ModelPart p = parts[ch.bone];
                if (p == null) continue;
                ch.sample(t, v);
                switch (ch.kind) {
                    // Blockbench -> game: x and y of the rotations and of the positions are the other way
                    case 0 -> {
                        p.xRot -= v[0] * Mth.DEG_TO_RAD * weight;
                        p.yRot -= v[1] * Mth.DEG_TO_RAD * weight;
                        p.zRot += v[2] * Mth.DEG_TO_RAD * weight;
                    }
                    case 1 -> {
                        p.x -= v[0] * weight;
                        p.y -= v[1] * weight;
                        p.z += v[2] * weight;
                    }
                    default -> {
                        p.xScale *= 1 + (v[0] - 1) * weight;
                        p.yScale *= 1 + (v[1] - 1) * weight;
                        p.zScale *= 1 + (v[2] - 1) * weight;
                    }
                }
            }
        }

        /** The value of one channel of one bone at a time (seconds since the start), or null when it has none. */
        public float[] value(int bone, int kind, float seconds) {
            for (Channel ch : channels) {
                if (ch.bone == bone && ch.kind == kind) {
                    float[] v = new float[3];
                    ch.sample(time(seconds), v);
                    return v;
                }
            }
            return null;
        }
    }

    static float catmullRom(float k, float p0, float p1, float p2, float p3) {
        return 0.5F * (2 * p1 + (-p0 + p2) * k + (2 * p0 - 5 * p1 + 4 * p2 - p3) * k * k + (-p0 + 3 * p1 - 3 * p2 + p3) * k * k * k);
    }

    /** The index of a bone in {@link #BONES} from its name (the last part of its path), -1 when it is not animated. */
    public static int bone(String name) {
        for (int i = 0; i < BONES.length; i++) {
            String b = BONES[i];
            if (b.equals(name) || b.endsWith("/" + name)) return i;
        }
        return -1;
    }

'''
ANIM_TAIL = '''    private SunSteedAnimations() {}
}
'''

if __name__ == '__main__':
    main()
