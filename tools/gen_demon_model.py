"""Writes the layer of the Demon of the Nether (alpha of the Nether) into DemonModel.java, from its Blockbench file, and
its textures: the texture painted in Blockbench and its glow (the glow painted by build_nether_demon.py, and the lava,
found by its colour).

Run from the project folder after a change of tools/models/demon_nether_alpha.bbmodel:
    python tools/gen_demon_model.py

The groups of the Blockbench file become the parts of the model (same names, same nesting), with the pivots, the
rotations and the texture offsets of the file (box UV), converted like the Blockbench Java exporter does. The animation
(DemonModel.setupAnim) relies on the names of the groups.
"""
import base64
import io
import json
import os
import re

import storm_model
from gen_storm_model import Writer
from gen_tortoise_model import Model

HERE = storm_model.HERE
BBMODEL = os.path.join(HERE, 'models', 'demon_nether_alpha.bbmodel')
PROJECT = os.path.dirname(HERE)
JAVA = os.path.join(PROJECT, 'src', 'main', 'java', 'com', 'yb', 'dragons', 'client', 'model', 'DemonModel.java')
TEXTURES = os.path.join(PROJECT, 'src', 'main', 'resources', 'assets', 'bdragon', 'textures', 'entity', 'alpha')
BEGIN = '        // <generated by tools/gen_demon_model.py>'
END = '        // </generated>'


def is_glowing(r, g, b):
    """The lava (orange and yellow) and the yellow eyes."""
    return r > 200 and g > 70 and b < 130 and r - b > 110


def main():
    model = Model(BBMODEL)
    root = [n for n in model.roots if model.groups[n['uuid']]['name'] == 'demon'][0]
    part = model.node_part(root, (0, 24, 0))
    w = Writer()
    w.part(part, 'root')
    w.lines.append('        return LayerDefinition.create(mesh, %d, %d);' % model.texture)
    src = open(JAVA, encoding='utf-8').read()
    pattern = re.compile(re.escape(BEGIN) + '.*?' + re.escape(END), re.S)
    if not pattern.search(src):
        raise SystemExit('markers not found in ' + JAVA)
    src = pattern.sub(lambda m: BEGIN + '\n' + '\n'.join(w.lines) + '\n' + END, src)
    with open(JAVA, 'w', encoding='utf-8', newline='\n') as out:
        out.write(src)

    from PIL import Image
    bb = json.load(open(BBMODEL, encoding='utf-8'))
    img = Image.open(io.BytesIO(base64.b64decode(bb['textures'][0]['source'].split(',', 1)[1]))).convert('RGBA')
    img.save(os.path.join(TEXTURES, 'nether_demon.png'))
    glow = Image.new('RGBA', img.size, (0, 0, 0, 0))
    # the glow painted by build_nether_demon.py (the eyes and the runes of the head of the dragon), if it fits
    painted = os.path.join(HERE, 'models', 'demon_nether_alpha_glow.png')
    if os.path.exists(painted):
        pg = Image.open(painted).convert('RGBA')
        if pg.size == img.size:
            glow = pg.copy()
    sp, gp = img.load(), glow.load()
    n = 0
    for y in range(img.size[1]):
        for x in range(img.size[0]):
            r, g, b, a = sp[x, y]
            if a > 0 and is_glowing(r, g, b):
                gp[x, y] = (r, g, b, 255)
                n += 1
    glow.save(os.path.join(TEXTURES, 'nether_demon_glow.png'))
    print('%d parts written, texture %dx%d, %d glowing pixels' % (w.n, model.texture[0], model.texture[1], n))


if __name__ == '__main__':
    main()
