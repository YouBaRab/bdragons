"""Writes the Moon Dragon (alpha of the moonlight) into the game, from its Blockbench file
tools/models/dragon_lune_alpha.bbmodel (started by tools/build_moon_alpha.py, then retouched by the author):

- the layer of MoonSerpentModel.java: the head (with its jaw and its crescent), the 25 elements of the spine like the
  Tempest Dragon (StormSpine), each with its sub groups (the arms on the torso, the back legs, the stars in orbit), and
  the star platform;
- the stars in orbit (their part and their turn in 60 seconds, from the animation stars_orbit);
- the texture (moon_dragon.png) and its glow (moon_dragon_glow.png: the moons, the stars, the platform and the eyes).

Run from the project folder after a change of the Blockbench file:
    python tools/gen_moon_model.py
"""
import base64
import io
import json
import os
import re

from PIL import Image

import storm_model
from gen_storm_model import Writer, f

HERE = storm_model.HERE
PROJECT = os.path.dirname(HERE)
BBMODEL = os.path.join(HERE, 'models', 'dragon_lune_alpha.bbmodel')
JAVA = os.path.join(PROJECT, 'src', 'main', 'java', 'com', 'yb', 'dragons', 'client', 'model', 'MoonSerpentModel.java')
TEXTURES = os.path.join(PROJECT, 'src', 'main', 'resources', 'assets', 'bdragon', 'textures', 'entity', 'alpha')
GLOWING = ('crescent', 'moon_ball', 'star', 'platform', 'eye_left', 'eye_right')


def replace(src, tag, code):
    begin = '        // <generated by tools/gen_moon_model.py: %s>' % tag
    end = '        // </generated: %s>' % tag
    pattern = re.compile(re.escape(begin) + '.*?' + re.escape(end), re.S)
    if not pattern.search(src):
        raise SystemExit('markers %s not found in %s' % (tag, JAVA))
    return pattern.sub(lambda m: begin + '\n' + code + '\n' + end, src)


def main():
    t = storm_model.Tree(BBMODEL)
    bones = [t.part('head', storm_model.ROOT_ORIGIN, 'all')]
    chain = set(storm_model.ELEMENTS) | {'head'}
    for name in storm_model.ELEMENTS:
        # its own sub groups (arms, legs, stars), not the next pieces of the chain nor the head
        bones.append(t.part(name, storm_model.ROOT_ORIGIN, tuple(g for g in t.subgroups(name) if g not in chain)))
    bones.append(t.part('star_platform', storm_model.ROOT_ORIGIN, 'all'))
    w = Writer()
    for b in bones:
        w.part(b, 'root')
    w.lines.append('        return LayerDefinition.create(mesh, %d, %d);' % t.texture)

    # the stars: the element that carries each one, and its turn in 60 seconds
    bb = json.load(open(BBMODEL, encoding='utf-8'))
    turns = {}
    for a in bb.get('animations', []):
        if not a['name'].endswith('stars_orbit'):
            continue
        for uid, an in a['animators'].items():
            keys = sorted((k for k in an['keyframes'] if k['channel'] == 'rotation'), key=lambda k: k['time'])
            if len(keys) >= 2:
                turns[an['name']] = (float(keys[-1]['data_points'][0]['z']) - float(keys[0]['data_points'][0]['z'])) / max(1e-6, keys[-1]['time'] - keys[0]['time'])
    stars = []
    for k, name in enumerate(storm_model.ELEMENTS):
        for sg in t.subgroups(name):
            if re.fullmatch(r'star\d+', sg):
                stars.append('            {%d, "%s", %s}' % (k, sg, f(turns.get(sg, 6.0))))
    star_code = ('        return new Object[][] {\n' + ',\n'.join(stars) + '};') if stars else '        return new Object[0][];'

    src = open(JAVA, encoding='utf-8').read()
    src = replace(src, 'layer', '\n'.join(w.lines))
    src = replace(src, 'stars', star_code)
    with open(JAVA, 'w', encoding='utf-8', newline='\n') as out:
        out.write(src)

    img = Image.open(io.BytesIO(base64.b64decode(bb['textures'][0]['source'].split(',', 1)[1]))).convert('RGBA')
    img.save(os.path.join(TEXTURES, 'moon_dragon.png'))
    glow = Image.new('RGBA', img.size, (0, 0, 0, 0))
    for e in bb['elements']:
        if e['name'] not in GLOWING:
            continue
        u, v = e.get('uv_offset') or [0, 0]
        sw, sh, sd = (int(-(-(e['to'][i] - e['from'][i]) // 1)) for i in range(3))
        box = (int(u), int(v), int(u) + 2 * (sw + sd), int(v) + sd + sh)
        glow.paste(img.crop(box), box[:2])
    glow.save(os.path.join(TEXTURES, 'moon_dragon_glow.png'))
    print('%d parts, %d stars, texture %dx%d' % (w.n, len(stars), *t.texture))


if __name__ == '__main__':
    main()
