"""Writes the layer of the Storm Serpent (alpha of the storm) into StormSerpentModel.java, from its Blockbench file.

Run from the project folder after a change of tools/models/dragon_tempete_alpha_v2.bbmodel:
    python tools/gen_storm_model.py
It also writes the texture painted in Blockbench to src/main/resources/assets/bdragon/textures/entity/alpha/storm_serpent.png
(run tools/gen_storm_textures.py again for its glow).
"""
import base64
import io
import json
import os
import re

import storm_model

JAVA = os.path.join(os.path.dirname(storm_model.HERE), 'src', 'main', 'java', 'com', 'yb', 'dragons', 'client', 'model',
                    'StormSerpentModel.java')
BEGIN = '        // <generated by tools/gen_storm_model.py>'
END = '        // </generated>'


def f(x):
    s = ('%.4f' % x).rstrip('0').rstrip('.')
    if s in ('-0', ''):
        s = '0'
    if '.' not in s:
        s += '.0'
    return s + 'F'


class Writer:
    def __init__(self):
        self.lines = []
        self.n = 0

    def part(self, p, parent_var):
        self.n += 1
        var = 'p%d' % self.n
        cubes = 'CubeListBuilder.create()'
        for (u, v, x, y, z, w, h, d) in p.cubes:
            cubes += '.texOffs(%d, %d).addBox(%s, %s, %s, %s, %s, %s)' % (u, v, f(x), f(y), f(z), f(w), f(h), f(d))
        ox, oy, oz = p.offset
        rx, ry, rz = p.rot
        if any(abs(a) > 1e-9 for a in p.rot):
            pose = 'PartPose.offsetAndRotation(%s, %s, %s, %s, %s, %s)' % (f(ox), f(oy), f(oz), f(rx), f(ry), f(rz))
        elif any(abs(a) > 1e-9 for a in p.offset):
            pose = 'PartPose.offset(%s, %s, %s)' % (f(ox), f(oy), f(oz))
        else:
            pose = 'PartPose.ZERO'
        decl = 'PartDefinition %s = ' % var if p.children else ''
        self.lines.append('        %s%s.addOrReplaceChild("%s", %s, %s);' % (decl, parent_var, p.name, cubes, pose))
        for c in p.children:
            self.part(c, var)


def main():
    model, bones = storm_model.build()
    w = Writer()
    for b in bones:
        w.part(b, 'root')
    code = '\n'.join(w.lines)
    src = open(JAVA, encoding='utf-8').read()
    pattern = re.compile(re.escape(BEGIN) + '.*?' + re.escape(END), re.S)
    if not pattern.search(src):
        raise SystemExit('markers not found in ' + JAVA)
    src = pattern.sub(lambda m: BEGIN + '\n' + code + '\n' + END, src)
    with open(JAVA, 'w', encoding='utf-8', newline='\n') as out:
        out.write(src)
    from PIL import Image
    bb = json.load(open(storm_model.BBMODEL, encoding='utf-8'))
    img = Image.open(io.BytesIO(base64.b64decode(bb['textures'][0]['source'].split(',', 1)[1])))
    img.save(os.path.join(os.path.dirname(storm_model.HERE), 'src', 'main', 'resources', 'assets', 'bdragon', 'textures',
                          'entity', 'alpha', 'storm_serpent.png'))
    print('%d parts written, texture %dx%d' % (w.n, *model.texture))


if __name__ == '__main__':
    main()
